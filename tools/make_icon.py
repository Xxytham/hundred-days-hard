"""Draws the app icon: a red bumper plate with two grip handles, a steel hub and "100" in Saira Condensed.
Writes Android vector drawables (full color, and single color for themed icons) and an SVG preview.
Usage: python3 tools/make_icon.py android/assets/fonts/<Saira Condensed 800>.woff2 android/res preview.svg  (needs fonttools, brotli)"""
import math, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

FONT, OUT_RES, OUT_SVG = sys.argv[1], sys.argv[2], sys.argv[3]
C = 54.0          # adaptive icon canvas is 108 x 108; keep the plate inside the 66-wide safe circle
R = 32.5

def text_path(txt, cx, cy, cap_h):
    f = TTFont(FONT); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f["head"].unitsPerEm
    cap = f["OS/2"].sCapHeight or 0.7 * upm
    s = cap_h / cap
    names = [cmap[ord(ch)] for ch in txt]
    track = -0.01 * upm
    width = sum(gs[n].width for n in names) + track * (len(names) - 1)
    pen = SVGPathPen(gs)
    x = cx - width * s / 2
    for n in names:
        # font units are y-up; flip and place the baseline so the cap height is centered on cy
        tp = TransformPen(pen, (s, 0, 0, -s, x, cy + cap_h / 2))
        gs[n].draw(tp)
        x += (gs[n].width + track) * s
    return pen.getCommands()

def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2*r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2*r:.2f},0 Z"

def slot(angle_deg, r_in, r_out, half_span_deg):
    """A kidney-shaped grip handle: a band between two radii with rounded ends."""
    a1, a2 = math.radians(angle_deg - half_span_deg), math.radians(angle_deg + half_span_deg)
    rc = (r_in + r_out) / 2; cap = (r_out - r_in) / 2
    P = lambda r, a: (C + r * math.cos(a), C + r * math.sin(a))
    o1, o2, i2, i1 = P(r_out, a1), P(r_out, a2), P(r_in, a2), P(r_in, a1)
    large = 1 if 2 * half_span_deg > 180 else 0
    return (f"M{o1[0]:.2f},{o1[1]:.2f} A{r_out},{r_out} 0 {large},1 {o2[0]:.2f},{o2[1]:.2f} "
            f"A{cap},{cap} 0 0,1 {i2[0]:.2f},{i2[1]:.2f} A{r_in},{r_in} 0 {large},0 {i1[0]:.2f},{i1[1]:.2f} "
            f"A{cap},{cap} 0 0,1 {o1[0]:.2f},{o1[1]:.2f} Z")

def arc(r, a_from, a_to):
    a1, a2 = math.radians(a_from), math.radians(a_to)
    p1 = (C + r * math.cos(a1), C + r * math.sin(a1)); p2 = (C + r * math.cos(a2), C + r * math.sin(a2))
    return f"M{p1[0]:.2f},{p1[1]:.2f} A{r},{r} 0 0,1 {p2[0]:.2f},{p2[1]:.2f}"

handles = slot(0, 21.0, 27.6, 27) + " " + slot(180, 21.0, 27.6, 27)
digits = text_path("100", C, C - 19.0, 11.6)
plate = circle(C, C, R)
hub_r, cap_r, hole_r = 7.2, 5.6, 2.3
TILT = 40  # turned clockwise a little, like a plate leaning on a rack

# ---------- full color (dark background layer behind it) ----------
def grad_linear(x1, y1, x2, y2, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" '
            f'android:endX="{x2}" android:endY="{y2}">{items}</gradient></aapt:attr>')

BG = "#14181D"
layers = [
    # rubber face: matte, with only a faint fall-off of light
    ("path", dict(d=plate), grad_linear(30, 22, 78, 86, [(0, "#E2304A"), (1, "#B51F33")])),
    ("path", dict(d=circle(C, C, R - 0.9), stroke="#94172A", sw="1.2", fill="none"), None),
    ("path", dict(d=circle(C, C, 11.2), stroke="#A21C2F", sw="1.0", fill="none"), None),
    # grip handles cut through the plate, so the background shows
    ("path", dict(d=handles, fill=BG), None),
    ("path", dict(d=digits, fill="#FFFFFF"), None),
    # slim steel sleeve: brushed, no shine spots
    ("path", dict(d=circle(C, C, hub_r)), grad_linear(47, 47, 61, 61, [(0, "#E6EAEE"), (1, "#8E979F")])),
    ("path", dict(d=circle(C, C, cap_r), stroke="#6F7880", sw="0.6", fill="none"), None),
    ("path", dict(d=circle(C, C, hole_r), fill=BG), None),
]

def vector(layers, size=108):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/make_icon.py: a red bumper plate with grip handles, a steel hub and "100". -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"',
           f'    android:width="{size}dp" android:height="{size}dp" android:viewportWidth="108" android:viewportHeight="108">']
    out.append(f'    <group android:pivotX="54" android:pivotY="54" android:rotation="{TILT}">')
    for _, a, g in layers:
        attrs = f'android:pathData="{a["d"]}"'
        if "fill" in a and a["fill"] != "none": attrs += f' android:fillColor="{a["fill"]}"'
        if "stroke" in a: attrs += f' android:strokeColor="{a["stroke"]}" android:strokeWidth="{a["sw"]}"'
        if a.get("cap"): attrs += ' android:strokeLineCap="round"'
        if a.get("alpha"): attrs += f' android:strokeAlpha="{a["alpha"]}"'
        if a.get("evenodd"): attrs += ' android:fillType="evenOdd"'
        if g: out.append(f'    <path {attrs}>{g}</path>')
        else: out.append(f'    <path {attrs}/>')
    out.append("    </group>")
    out.append("</vector>\n")
    return "\n".join(out)

open(OUT_RES + "/drawable/ic_plate.xml", "w").write(vector(layers))

# ---------- single color: the system tints it to match the wallpaper (themed icons) ----------
mono = [
    ("path", dict(d=plate + " " + handles + " " + digits + " " + circle(C, C, hub_r + 0.9), fill="#FFFFFF", evenodd=True), None),
    ("path", dict(d=circle(C, C, hub_r) + " " + circle(C, C, hole_r), fill="#FFFFFF", evenodd=True), None),
]
open(OUT_RES + "/drawable/ic_plate_mono.xml", "w").write(vector(mono))
# status bar icon for notifications: the same single-color plate, enlarged to fill a 24dp box
stat = vector(mono, 24).replace('android:rotation="', 'android:scaleX="1.55" android:scaleY="1.55" android:rotation="')
open(OUT_RES + "/drawable/ic_stat_plate.xml", "w").write(stat)

# ---------- SVG preview of both ----------
def svg_layers(layers, bg):
    s = [f'<rect width="108" height="108" fill="{bg}"/><g transform="rotate({TILT} 54 54)">']
    gid = 0
    for _, a, g in layers:
        extra = ""
        fill = a.get("fill", "none")
        if g:
            gid += 1
            import re
            sx, sy, ex, ey = re.findall(r'android:(?:start|end)[XY]="([\d.]+)"', g)
            stops = re.findall(r'offset="([\d.]+)" android:color="(#\w+)"', g)
            s.append(f'<defs><linearGradient id="g{gid}" gradientUnits="userSpaceOnUse" x1="{sx}" y1="{sy}" x2="{ex}" y2="{ey}">' +
                     "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in stops) + "</linearGradient></defs>")
            fill = f"url(#g{gid})"
        if "stroke" in a: extra += f' stroke="{a["stroke"]}" stroke-width="{a["sw"]}"'
        if a.get("cap"): extra += ' stroke-linecap="round"'
        if a.get("alpha"): extra += f' stroke-opacity="{a["alpha"]}"'
        if a.get("evenodd"): extra += ' fill-rule="evenodd"'
        s.append(f'<path d="{a["d"]}" fill="{fill}"{extra}/>')
    s.append("</g>")
    return "".join(s)
open(OUT_SVG, "w").write(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 340 108" width="1360" height="432">'
    f'<g><clipPath id="m1"><circle cx="54" cy="54" r="40"/></clipPath><g clip-path="url(#m1)">{svg_layers(layers, BG)}</g></g>'
    f'<g transform="translate(116,0)"><clipPath id="m2"><rect x="14" y="14" width="80" height="80" rx="22"/></clipPath><g clip-path="url(#m2)">{svg_layers(layers, BG)}</g></g>'
    f'<g transform="translate(232,0)"><clipPath id="m3"><circle cx="54" cy="54" r="40"/></clipPath><g clip-path="url(#m3)"><rect width="108" height="108" fill="#DCE7D5"/>'
    + svg_layers(mono, "#DCE7D5").replace('fill="#FFFFFF"', 'fill="#2F4A2A"') + "</g></g></svg>")
print("ok")
open(OUT_SVG.replace(".svg", "-icon.svg"), "w").write(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">' + svg_layers(layers, BG) + "</svg>")
